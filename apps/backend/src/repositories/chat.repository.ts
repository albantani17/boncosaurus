import { and, asc, desc, eq, sql } from 'drizzle-orm';
import { db } from '../db';
import { chatConversations, chatMessages } from '../db/schema';
import type {
  ChatConversation,
  ChatConversationPatch,
  ChatMessageRecord,
  NewChatConversation,
  NewChatMessage
} from '../types/ai.types';

export type ChatRepository = {
  listConversations(workspaceId: string, userId: string): Promise<ChatConversation[]>;
  findConversation(workspaceId: string, userId: string, id: string): Promise<ChatConversation | undefined>;
  insertConversation(values: NewChatConversation): Promise<ChatConversation>;
  updateConversation(
    workspaceId: string,
    id: string,
    patch: ChatConversationPatch
  ): Promise<ChatConversation | undefined>;
  deleteConversation(workspaceId: string, id: string): Promise<void>;
  listMessages(workspaceId: string, conversationId: string): Promise<ChatMessageRecord[]>;
  findMessage(workspaceId: string, conversationId: string, id: string): Promise<ChatMessageRecord | undefined>;
  saveMessage(values: NewChatMessage): Promise<void>;
};

const conversationInWorkspace = (workspaceId: string, id: string) =>
  and(eq(chatConversations.workspaceId, workspaceId), eq(chatConversations.id, id));

const messagesOf = (workspaceId: string, conversationId: string) =>
  and(eq(chatMessages.workspaceId, workspaceId), eq(chatMessages.conversationId, conversationId));

export const chatRepository: ChatRepository = {
  listConversations: (workspaceId, userId) =>
    db
      .select()
      .from(chatConversations)
      .where(and(eq(chatConversations.workspaceId, workspaceId), eq(chatConversations.userId, userId)))
      .orderBy(desc(chatConversations.updatedAt), desc(chatConversations.id)),

  async findConversation(workspaceId, userId, id) {
    const [row] = await db
      .select()
      .from(chatConversations)
      .where(and(conversationInWorkspace(workspaceId, id), eq(chatConversations.userId, userId)));
    return row;
  },

  async insertConversation(values) {
    const [row] = await db.insert(chatConversations).values(values).returning();
    return row!;
  },

  async updateConversation(workspaceId, id, patch) {
    const [row] = await db
      .update(chatConversations)
      .set({ ...patch, updatedAt: new Date() })
      .where(conversationInWorkspace(workspaceId, id))
      .returning();
    return row;
  },

  async deleteConversation(workspaceId, id) {
    await db.delete(chatConversations).where(conversationInWorkspace(workspaceId, id));
  },

  listMessages: (workspaceId, conversationId) =>
    db
      .select()
      .from(chatMessages)
      .where(messagesOf(workspaceId, conversationId))
      .orderBy(asc(chatMessages.createdAt), asc(chatMessages.id)),

  async findMessage(workspaceId, conversationId, id) {
    const [row] = await db
      .select()
      .from(chatMessages)
      .where(and(messagesOf(workspaceId, conversationId), eq(chatMessages.id, id)));
    return row;
  },

  // Message ids are generated by the server, so an id conflict is always the same message being rewritten.
  async saveMessage(values) {
    await db
      .insert(chatMessages)
      .values(values)
      .onConflictDoUpdate({
        target: chatMessages.id,
        set: { parts: values.parts },
        setWhere: sql`${chatMessages.conversationId} = ${values.conversationId}`
      });
  }
};
